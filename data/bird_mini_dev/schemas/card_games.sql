CREATE TABLE "foreign_data" (
    "id" integer PRIMARY KEY,
    "flavorText" text,
    "language" text,
    "multiverseid" integer,
    "name" text,
    "text" text,
    "type" text,
    "uuid" text,
    FOREIGN KEY ("uuid") REFERENCES "cards" ("uuid")
);

CREATE TABLE "legalities" (
    "id" integer PRIMARY KEY,
    "format" text,
    "status" text,
    "uuid" text,
    FOREIGN KEY ("uuid") REFERENCES "cards" ("uuid")
);

CREATE TABLE "sets" (
    "id" integer PRIMARY KEY,
    "baseSetSize" integer,
    "block" text,
    "booster" text,
    "code" text,
    "isFoilOnly" integer,
    "isForeignOnly" integer,
    "isNonFoilOnly" integer,
    "isOnlineOnly" integer,
    "isPartialPreview" integer,
    "keyruneCode" text,
    "mcmId" integer,
    "mcmIdExtras" integer,
    "mcmName" text,
    "mtgoCode" text,
    "name" text,
    "parentCode" text,
    "releaseDate" date,
    "tcgplayerGroupId" integer,
    "totalSetSize" integer,
    "type" text
);

CREATE TABLE "set_translations" (
    "id" integer PRIMARY KEY,
    "language" text,
    "setCode" text,
    "translation" text,
    FOREIGN KEY ("setCode") REFERENCES "sets" ("code")
);

CREATE TABLE "rulings" (
    "id" integer PRIMARY KEY,
    "date" date,
    "text" text,
    "uuid" text,
    FOREIGN KEY ("uuid") REFERENCES "cards" ("uuid")
);
